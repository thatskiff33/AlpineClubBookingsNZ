import type { PRIVACY_RETENTION_CLASSIFICATION } from "@/lib/privacy-retention-classification";

/**
 * Where each personal model goes in a subject access export (#4915,
 * `INV-PRIV-023`).
 *
 * The keys are exactly the models `PRIVACY_RETENTION_CLASSIFICATION` marks
 * `personal`: the `satisfies` below makes a new personal model a type error
 * until it is placed, and `subject-access-export-census.test.ts` holds the same
 * to the classification at run time. A value is either the export section that
 * carries the subject's rows, `additionalRecords.<Model>` for a model with its
 * own subject-filtered list, or `{ excluded }` with the reason the file gives.
 */
type Classification = typeof PRIVACY_RETENTION_CLASSIFICATION;
export type PersonalModel = {
  [K in keyof Classification]: Classification[K] extends "personal" ? K : never;
}[keyof Classification];

