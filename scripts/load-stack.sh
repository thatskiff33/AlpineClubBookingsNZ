#!/usr/bin/env bash
# Stands up the throwaway load-test stack for the k6 harness (#4940).
#
#   scripts/load-stack.sh prepare   # E2E stack + volume seed + Stripe stub, cron off
#   scripts/load-stack.sh cron-on   # recreate the app with the scheduler running
#   scripts/load-stack.sh cron-off  # back to the default profile
#   scripts/load-stack.sh logs      # app and stub logs
#   scripts/load-stack.sh down      # stop the stack, remove its volumes and keys
#
# Read-outs the smoke run uses, so it keeps no second copy of any of them:
# base-url, demo-password, volume-members, cron-secret, profile.
#
# It is the E2E stack (scripts/e2e-stack.sh) run as its own compose project,
# load-issue4940, on the same default ports (app on http://localhost:3001,
# Postgres on 5433), so it cannot run beside the E2E stack. It adds three things:
#
#  - a club-sized history from prisma/load-volume-seed.ts, behind the load
#    harness's own database guard;
#  - a second lodge (E2E_MULTI_LODGE=1), so the write scenarios span lodges;
#  - load/compose.stripe-stub.yml, which answers for api.stripe.com inside the
#    compose network. The Stripe keys the stack holds are generated here, used
#    only against that stub, and thrown away by `down`.
#
# The env file is a COPY of the E2E one (E2E_ENV_FILE, default .env.staging)
# with the three Stripe values replaced, written to .artifacts/load-stub/
# (gitignored). Live Stripe keys in the source file are refused outright.
#
# Safety: only a compose project named load-* is accepted, so it never touches
# the E2E or production projects, or port 5432, and no live provider is called.
set -euo pipefail

cd "$(dirname "$0")/.."

SOURCE_ENV_FILE="${E2E_ENV_FILE:-.env.staging}"
COMPOSE_PROJECT="${E2E_COMPOSE_PROJECT:-load-issue4940}"
export E2E_COMPOSE_PROJECT="$COMPOSE_PROJECT"
# `prepare` drops the project's schema and `down` deletes its volumes, so only
# a project named as a load stack is accepted: production and staging project
# names vary by deploy directory and cannot be listed here.
if [[ ! "$COMPOSE_PROJECT" =~ ^load-[a-z0-9][a-z0-9_-]*$ ]]; then
  echo "Refusing E2E_COMPOSE_PROJECT=$COMPOSE_PROJECT: a load stack's project name starts with load-." >&2
  exit 1
fi
STUB_DIR=".artifacts/load-stub"
TLS_DIR="$STUB_DIR/tls"
LOAD_ENV_FILE="$STUB_DIR/load.env"

# shellcheck source=scripts/lib/compose-env-file.sh
. scripts/lib/compose-env-file.sh

stub_compose() {
  docker compose --env-file "$LOAD_ENV_FILE" -p "$COMPOSE_PROJECT" \
    -f docker-compose.yml -f docker-compose.staging.yml -f load/compose.stripe-stub.yml "$@"
}

cron_compose() {
  docker compose --env-file "$LOAD_ENV_FILE" -p "$COMPOSE_PROJECT" \
    -f docker-compose.yml -f docker-compose.staging.yml -f load/compose.stripe-stub.yml -f load/compose.cron-on.yml "$@"
}

write_stub_tls() {
  echo "==> Generating the stub's throwaway TLS certificate"
  rm -rf "$TLS_DIR"
  mkdir -p "$TLS_DIR"
  local work
  work="$(mktemp -d "$STUB_DIR/tls-work.XXXXXX")"
  openssl req -x509 -newkey rsa:2048 -nodes -days 7 -subj "/CN=load-test Stripe stub CA" \
    -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign" \
    -keyout "$work/ca-key.pem" -out "$TLS_DIR/ca.pem" 2>/dev/null
  openssl req -newkey rsa:2048 -nodes -subj "/CN=api.stripe.com" \
    -keyout "$TLS_DIR/stub-key.pem" -out "$work/stub.csr" 2>/dev/null
  printf 'subjectAltName=DNS:api.stripe.com\nbasicConstraints=CA:FALSE\nextendedKeyUsage=serverAuth\n' \
    > "$work/ext.cnf"
  openssl x509 -req -in "$work/stub.csr" -CA "$TLS_DIR/ca.pem" -CAkey "$work/ca-key.pem" \
    -CAcreateserial -CAserial "$work/ca.srl" -days 7 -extfile "$work/ext.cnf" -out "$TLS_DIR/stub.pem" 2>/dev/null
  # The CA key is discarded, so the CA the app trusts can sign nothing else.
  rm -rf "$work"
  # Readable by the stub's unprivileged `node` user, whatever uid wrote it.
  chmod 0644 "$TLS_DIR/ca.pem" "$TLS_DIR/stub.pem" "$TLS_DIR/stub-key.pem"
  openssl verify -CAfile "$TLS_DIR/ca.pem" "$TLS_DIR/stub.pem" >/dev/null
}

write_load_env() {
  if [[ ! -f "$SOURCE_ENV_FILE" ]]; then
    echo "Missing $SOURCE_ENV_FILE — copy .env.staging.example and adjust (see docs/LOAD_TESTING.md)." >&2
    exit 1
  fi
  if grep -Eq '^[[:space:]]*[A-Z_]*STRIPE[A-Z_]*=[[:space:]]*(sk|pk|rk)_live' "$SOURCE_ENV_FILE"; then
    echo "Refusing to run: live Stripe keys found in $SOURCE_ENV_FILE. The load stack only ever talks to its stub." >&2
    exit 1
  fi
  echo "==> Writing $LOAD_ENV_FILE with generated stub-only Stripe keys"
  mkdir -p "$STUB_DIR"
  local suffix
  suffix="$(openssl rand -hex 16)"
  {
    grep -Ev '^[[:space:]]*(STRIPE_SECRET_KEY|NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY|STRIPE_WEBHOOK_SECRET)=' \
      "$SOURCE_ENV_FILE" || true
    printf '\n# Generated by scripts/load-stack.sh: valid only against the local Stripe stub.\n'
    printf 'STRIPE_SECRET_KEY=sk_test_loadstub_%s\n' "$suffix"
    printf 'NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY=pk_test_loadstub_%s\n' "$suffix"
    printf 'STRIPE_WEBHOOK_SECRET=whsec_loadstub_%s\n' "$suffix"
  } > "$LOAD_ENV_FILE"
  chmod 0600 "$LOAD_ENV_FILE"
}

seed_volume() {
  read_compose_env_file "$LOAD_ENV_FILE"
  local host_database_url="postgresql://tac:${DB_PASSWORD}@localhost:${STAGING_POSTGRES_PORT:-5433}/tacbookings"
  echo "==> Seeding load volume"
  LOAD_TEST_CONFIRM_TARGET=1 ALLOW_DEMO_SEED=1 DATABASE_URL="$host_database_url" \
    pnpm exec tsx --conditions=react-server prisma/load-volume-seed.ts
}

prepare() {
  write_stub_tls
  write_load_env
  read_compose_env_file "$LOAD_ENV_FILE"
  # Before e2e-stack can reset any schema, validate BOTH published ports using
  # the same target guard as the scenarios and the volume seeder.
  export DATABASE_URL="postgresql://tac:${DB_PASSWORD}@localhost:${STAGING_POSTGRES_PORT:-5433}/tacbookings"
  export BASE_URL="http://localhost:${STAGING_HTTP_PORT:-3001}"
  LOAD_TEST_CONFIRM_TARGET=1 node --input-type=module -e '
    import { assertSafeDatabaseTarget, assertSafeTarget } from "./load/lib/target-guard.js";
    assertSafeDatabaseTarget(process.env); assertSafeTarget(process.env);
  '
  E2E_ENV_FILE="$LOAD_ENV_FILE" E2E_MULTI_LODGE=1 E2E_LOAD_STUB=1 bash scripts/e2e-stack.sh prepare
  seed_volume
  echo "==> Recreating the app beside the Stripe stub (cron off)"
  stub_compose up -d --wait app stripe-stub
}

require_prepared() {
  if [[ ! -f "$LOAD_ENV_FILE" || ! -f "$TLS_DIR/ca.pem" ]]; then
    echo "No load stack here — run scripts/load-stack.sh prepare first." >&2
    exit 1
  fi
}

# CPU limit of one service's running container, in cores ("uncapped" if none).
container_cpus() {
  local id nano
  id="$(stub_compose ps -q "$1")"
  nano="$(docker inspect --format '{{.HostConfig.NanoCpus}}' "$id")"
  if [[ "$nano" == "0" ]]; then echo '"uncapped"'; else node -e "console.log($nano / 1e9)"; fi
}

# Volume members the seeder wrote, counted in this stack's own database. The
# profile records this figure and the smoke run sizes its member pool from it,
# so neither repeats the seeder's default. The pattern comes from the same two
# constants the seeder and k6 use, so it matches exactly the accounts they name.
volume_member_count() {
  # Callers run this inside $(...), where bash clears `set -e`, so every step
  # checks itself: an empty pattern would otherwise count 0 and look like a result.
  local pattern count
  pattern="$(pnpm exec tsx -e 'import { DEMO_SEED_DOMAIN } from "./src/lib/demo-seed-guard"; import { LOAD_VOLUME_EMAIL_PREFIX } from "./load/lib/volume-users.js"; console.log(LOAD_VOLUME_EMAIL_PREFIX + "%@" + DEMO_SEED_DOMAIN)')" || return 1
  if [[ -z "$pattern" ]]; then
    echo "Could not work out the volume member address pattern." >&2
    return 1
  fi
  count="$(stub_compose exec -T postgres psql -U tac -d tacbookings -tA -v ON_ERROR_STOP=1 \
    -c "SELECT count(*) FROM \"Member\" WHERE email LIKE '${pattern}'")" || return 1
  if [[ ! "$count" =~ ^[0-9]+$ ]]; then
    echo "Expected a member count from Postgres, got: $count" >&2
    return 1
  fi
  printf '%s' "$count"
}

case "${1:-}" in
  prepare)
    prepare
    ;;
  cron-on)
    require_prepared
    echo "==> Recreating the app with the scheduler running"
    cron_compose up -d --wait app stripe-stub
    ;;
  cron-off)
    require_prepared
    stub_compose up -d --wait app stripe-stub
    ;;
  require-running)
    require_prepared
    # The app and stub must be up in THIS load project before any k6 run, so
    # leftover env files from a failed prepare cannot send load elsewhere.
    for service in app stripe-stub; do
      if [[ -z "$(stub_compose ps -q --status running "$service")" ]]; then
        echo "The $service service is not running in compose project $COMPOSE_PROJECT." >&2
        exit 1
      fi
    done
    ;;
  profile)
    require_prepared
    # Values from the actual running containers, without emitting the database URL.
    # volumeMembers is the count in the database, whatever the seeder was told.
    # Read first, so a failed count stops the profile rather than recording 0.
    volume_members="$(volume_member_count)"
    stub_compose exec -T -e VOLUME_MEMBERS="$volume_members" -e PEAK_VUS="${PEAK_VUS:-}" \
      -e APP_CPUS="$(container_cpus app)" -e POSTGRES_CPUS="$(container_cpus postgres)" app node -e '
      const os = require("node:os");
      const pool = new URL(process.env.DATABASE_URL).searchParams.get("connection_limit");
      console.log(JSON.stringify({ cores: os.availableParallelism(), pool: pool ? Number(pool) : "pg default",
        appCpus: JSON.parse(process.env.APP_CPUS), postgresCpus: JSON.parse(process.env.POSTGRES_CPUS),
        vus: Number(process.env.PEAK_VUS) || "unset", volumeMembers: Number(process.env.VOLUME_MEMBERS) }, null, 2));
    '
    ;;
  cron-secret)
    require_prepared
    read_compose_env_file "$LOAD_ENV_FILE"
    printf '%s' "$CRON_SECRET"
    ;;
  base-url)
    require_prepared
    # The port the app was published on, as `prepare` guarded it.
    read_compose_env_file "$LOAD_ENV_FILE"
    printf 'http://localhost:%s' "${STAGING_HTTP_PORT:-3001}"
    ;;
  demo-password)
    require_prepared
    # The password the seeders hashed: the stack env file overrides the caller's
    # shell, as it does for them, then the seeders' own default applies.
    read_compose_env_file "$LOAD_ENV_FILE"
    pnpm exec tsx --conditions=react-server -e 'import { demoSeedPassword } from "./prisma/demo-seed-writers"; process.stdout.write(demoSeedPassword())'
    ;;
  volume-members)
    require_prepared
    volume_member_count
    ;;
  logs)
    require_prepared
    stub_compose logs --tail 200 app stripe-stub
    ;;
  down)
    if [[ -f "$LOAD_ENV_FILE" ]]; then
      stub_compose down -v
      E2E_ENV_FILE="$LOAD_ENV_FILE" E2E_LOAD_STUB=1 bash scripts/e2e-stack.sh down
    fi
    rm -rf "$STUB_DIR"
    ;;
  *)
    echo "Usage: $0 {prepare|cron-on|cron-off|require-running|profile|cron-secret|base-url|demo-password|volume-members|logs|down}" >&2
    exit 1
    ;;
esac
