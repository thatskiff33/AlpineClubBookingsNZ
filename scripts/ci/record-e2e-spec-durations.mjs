#!/usr/bin/env node
// Rewrite scripts/ci/e2e-spec-durations.mjs from one E2E run's logs, so the
// shards stay balanced as specs grow and shrink:
//
//   gh run view <run-id> --log > e2e.log
//   node scripts/ci/record-e2e-spec-durations.mjs e2e.log
//
// Use a green run of every shard (the log of all its jobs, as `gh run view
// --log` prints it). A spec file's time is the wall clock its tests took on the
// runner, hooks and retries included: each test's share is the time since the
// line before it in the same job. `auth.setup.ts` is left out because every
// shard runs it.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const DURATIONS_FILE = path.join(import.meta.dirname, "e2e-spec-durations.mjs");
// `<job>\t<step>\t<ISO timestamp> <list-reporter line>`, the list reporter's
// line being `  ✓  12 [chromium] › e2e/booking.spec.ts:20:7 › title (5.3s)`.
const LINE = /^([^\t]+)\t[^\t]*\t(\S+) .*?\[(?:chromium|pre-setup)\] › e2e\/(\S+?):\d+:\d+ › .*\((\d+(?:\.\d+)?)(ms|s|m)\)\s*$/;
const UNIT_SECONDS = { ms: 0.001, s: 1, m: 60 };

/** Seconds per spec file (relative to `e2e/`), from `gh run view --log` text. */
export function specSecondsFromLog(text) {
  const seconds = {};
  const lastSeen = new Map();
  for (const line of text.split("\n")) {
    const match = LINE.exec(line);
    if (!match) continue;
    const [, job, stamp, file, value, unit] = match;
    const at = Date.parse(stamp);
    const previous = lastSeen.get(job);
    // The first test a job logs has no line before it; its own duration stands in.
    const spent = previous === undefined ? Number(value) * UNIT_SECONDS[unit] : (at - previous) / 1000;
    lastSeen.set(job, at);
    seconds[file] = (seconds[file] ?? 0) + spent;
  }
  return Object.fromEntries(Object.entries(seconds).sort(([a], [b]) => a.localeCompare(b)).map(([file, value]) => [file, Math.round(value * 10) / 10]));
}

export function renderDurationsModule(seconds, source) {
  const entries = Object.entries(seconds).map(([file, value]) => `  ${JSON.stringify(file)}: ${value},`);
  return [
    "// Measured seconds per E2E spec file, which scripts/ci/e2e-spec-shard.mjs uses",
    "// to balance the shards. Generated by scripts/ci/record-e2e-spec-durations.mjs;",
    "// rerun it rather than editing by hand. A spec missing here is dealt as if it",
    "// took the median, so a new spec never needs an entry to run.",
    `// Source: ${source}.`,
    "export const E2E_SPEC_SECONDS = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const logFile = process.argv[2];
  if (!logFile) {
    console.error("Usage: node scripts/ci/record-e2e-spec-durations.mjs <gh-run-log-file> [source note]");
    process.exit(1);
  }
  const seconds = specSecondsFromLog(readFileSync(logFile, "utf8"));
  if (Object.keys(seconds).length === 0) {
    console.error(`No Playwright list-reporter lines found in ${logFile}.`);
    process.exit(1);
  }
  writeFileSync(DURATIONS_FILE, renderDurationsModule(seconds, process.argv[3] ?? `E2E run logs in ${path.basename(logFile)}`));
  console.log(`Wrote ${Object.keys(seconds).length} spec durations to ${path.relative(process.cwd(), DURATIONS_FILE)}.`);
}
